import { createHash } from "node:crypto";
import { access, mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const THUMBNAIL_WIDTHS = [384, 640, 828, 1080, 1440];
const WEBP_OPTIONS = { quality: 80, effort: 4 };
// Changing the encoding recipe must also change immutable thumbnail URLs.
const recipe = createHash("sha256").update(JSON.stringify({
  version: 1, widths: THUMBNAIL_WIDTHS, webp: WEBP_OPTIONS, encoder: sharp.versions,
})).digest("hex").slice(0, 12);

async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

// Generate responsive thumbnails at build time, never through /_next/image.
// Content-addressed originals and thumbnails can survive unrelated deployments.
// Only the small metadata manifest belongs in server functions.
export async function generateImageMetadata(root) {
  const entriesRoot = path.join(root, "Entries");
  const assetsRoot = path.join(root, "public", "feed-media");
  await mkdir(assetsRoot, { recursive: true });
  const assetNames = new Set();
  const metadata = {};
  for (const directory of await readdir(entriesRoot, { withFileTypes: true })) {
    if (!directory.isDirectory() || directory.name.startsWith(".")) continue;
    const entryRoot = path.join(entriesRoot, directory.name);
    let entry;
    try {
      entry = JSON.parse(
        (await readFile(path.join(entryRoot, "index.json"), "utf8")).replace(/^\uFEFF/, ""),
      );
    } catch (error) {
      if (error.code === "ENOENT") continue;
      throw error;
    }
    if (!entry.image) continue;
    const buffer = await readFile(path.join(entryRoot, entry.image));
    const inputMetadata = await sharp(buffer).metadata();
    const { width, height } = inputMetadata.autoOrient;
    const version = createHash("sha256").update(buffer).digest("hex");
    const assetName = `${version}${path.extname(entry.image).toLowerCase()}`;
    const originalPath = path.join(assetsRoot, assetName);
    if (!await exists(originalPath)) await writeFile(originalPath, buffer);
    assetNames.add(assetName);

    // Never upscale a source or exceed WebP's dimension limit for tall images.
    const maxWidth = Math.min(width, 1440, Math.floor(16383 * width / height));
    const widths = [...new Set([...THUMBNAIL_WIDTHS.filter(size => size < maxWidth), maxWidth])];
    const thumbnails = [];
    for (const thumbnailWidth of widths) {
      const name = `${version}-${recipe}-${thumbnailWidth}.webp`;
      const thumbnailPath = path.join(assetsRoot, name);
      if (!await exists(thumbnailPath)) {
        // Encode fully before writing so a failed encoder never leaves a
        // partial file that a later build would mistake for a cached asset.
        const thumbnail = await sharp(buffer, { animated: true })
          .autoOrient()
          .resize({ width: thumbnailWidth, withoutEnlargement: true })
          .webp(WEBP_OPTIONS)
          .toBuffer();
        await writeFile(thumbnailPath, thumbnail);
      }
      assetNames.add(name);
      thumbnails.push({ url: `/feed-media/${name}`, width: thumbnailWidth });
    }
    const defaultThumbnail = thumbnails.find(image => image.width >= 640) || thumbnails.at(-1);
    metadata[`${directory.name}/${entry.image}`] = {
      width,
      height,
      version,
      url: `/feed-media/${assetName}`,
      thumbnail: {
        src: defaultThumbnail.url,
        srcSet: thumbnails.map(image => `${image.url} ${image.width}w`).join(", "),
      },
    };
  }

  // Prune only files generated by this script, never unrelated public assets.
  for (const asset of await readdir(assetsRoot, { withFileTypes: true })) {
    if (asset.isFile() && /^[a-f0-9]{64}(?:-[a-f0-9]{12}-\d+)?\.[a-z0-9]+$/.test(asset.name) && !assetNames.has(asset.name)) {
      await unlink(path.join(assetsRoot, asset.name));
    }
  }

  const output = path.join(root, ".generated");
  await mkdir(output, { recursive: true });
  await writeFile(path.join(output, "image-metadata.json"), JSON.stringify(metadata));
  console.log(`Prepared static originals and responsive thumbnails for ${Object.keys(metadata).length} feed images.`);
  return metadata;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateImageMetadata(process.cwd());
}
